#!/usr/bin/env bash
# sync.sh — Wire ai-skills to Claude Code, Gemini CLI, and Cursor
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")" && pwd)"
SKILLS_DIR="$REPO_DIR/skills"
INSTRUCTIONS_DIR="$REPO_DIR/instructions"

CLAUDE_DIR="$HOME/.claude"
GEMINI_DIR="$HOME/.gemini"
CURSOR_RULES="$HOME/.cursorrules"

# ── helpers ──────────────────────────────────────────────────────────────────

info()    { echo "  [ok] $*"; }
warn()    { echo "  [!!] $*"; }
section() { echo; echo "── $* ──"; }

backup() {
  local target="$1"
  if [[ -e "$target" && ! -L "$target" ]]; then
    local bak="${target}.bak.$(date +%Y%m%d%H%M%S)"
    mv "$target" "$bak"
    warn "Backed up existing $(basename "$target") → $bak"
  fi
}

# Concatenate all *.md files in $INSTRUCTIONS_DIR into a single string,
# prefixed with a managed-by header.
build_instructions() {
  local tool="$1"
  echo "# AI Instructions — managed by ~/apps/ai-skills (sync.sh)"
  echo "# Tool: $tool  |  Source: $INSTRUCTIONS_DIR"
  echo "# Edit the source files and re-run sync.sh — do not edit this file directly."
  echo
  for f in "$INSTRUCTIONS_DIR"/*.md; do
    [[ -f "$f" ]] || continue
    echo
    cat "$f"
    echo
  done
}

# ── Claude Code ───────────────────────────────────────────────────────────────

section "Claude Code"

# Skills: symlink the whole directory so new skills appear automatically
CLAUDE_SKILLS="$CLAUDE_DIR/skills"
if [[ -L "$CLAUDE_SKILLS" ]]; then
  current_target="$(readlink "$CLAUDE_SKILLS")"
  if [[ "$current_target" == "$SKILLS_DIR" ]]; then
    info "~/.claude/skills symlink already correct"
  else
    warn "~/.claude/skills points to $current_target — updating"
    rm "$CLAUDE_SKILLS"
    ln -s "$SKILLS_DIR" "$CLAUDE_SKILLS"
    info "~/.claude/skills → $SKILLS_DIR"
  fi
elif [[ -d "$CLAUDE_SKILLS" ]]; then
  warn "~/.claude/skills is a real directory — rename it manually if you want to replace it, then re-run sync.sh"
else
  ln -s "$SKILLS_DIR" "$CLAUDE_SKILLS"
  info "~/.claude/skills → $SKILLS_DIR"
fi

# Global CLAUDE.md
CLAUDE_MD="$CLAUDE_DIR/CLAUDE.md"
backup "$CLAUDE_MD"
build_instructions "Claude Code" > "$CLAUDE_MD"
info "~/.claude/CLAUDE.md written"

# ── Gemini CLI ────────────────────────────────────────────────────────────────

section "Gemini CLI"

mkdir -p "$GEMINI_DIR"
GEMINI_MD="$GEMINI_DIR/GEMINI.md"
backup "$GEMINI_MD"
build_instructions "Gemini CLI" > "$GEMINI_MD"
info "~/.gemini/GEMINI.md written"

# ── Cursor ────────────────────────────────────────────────────────────────────

section "Cursor"

backup "$CURSOR_RULES"
build_instructions "Cursor" > "$CURSOR_RULES"
info "~/.cursorrules written"

# ── Done ─────────────────────────────────────────────────────────────────────

echo
echo "Done. To add a skill: drop a .md file in $SKILLS_DIR"
echo "To update global instructions: edit files in $INSTRUCTIONS_DIR, then re-run sync.sh"
