#!/usr/bin/env bash
# sync.sh — Wire ai-toolbox to Claude Code, Gemini CLI, Cursor, and Hermes
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")" && pwd)"
SKILLS_DIR="$REPO_DIR/skills"
INSTRUCTIONS_DIR="$REPO_DIR/instructions"

CLAUDE_DIR="$HOME/.claude"
GEMINI_DIR="$HOME/.gemini"
HERMES_DIR="$HOME/.hermes"
CURSOR_RULES="$HOME/.cursorrules"

# ── helpers ──────────────────────────────────────────────────────────────────

info()    { echo "  [ok] "; }
warn()    { echo "  [!!] "; }
section() { echo; echo "──  ──"; }

backup() {
  local target="$1"
  if [[ -e "$target" && ! -L "$target" ]]; then
    local bak="${target}.bak.$(date +%Y%m%d%H%M%S)"
    mv "$target" "$bak"
    warn "Backed up existing $(basename "$target") → $bak"
  fi
}

# Concatenate all *.md files in $INSTRUCTIONS_DIR into a single string,
# prefixed with a managed-by header.
build_instructions() {
  local tool="$1"
  echo "# AI Instructions — managed by ~/apps/ai-toolbox (sync.sh)"
  echo "# Tool: $tool  |  Source: $INSTRUCTIONS_DIR"
  echo "# Edit the source files and re-run sync.sh — do not edit this file directly."
  echo
  for f in "$INSTRUCTIONS_DIR"/*.md; do
    [[ -f "$f" ]] || continue
    echo
    cat "$f"
    echo
  done
}

# ── Claude Code ───────────────────────────────────────────────────────────────

section "Claude Code"

# Skills: copy each *.md into ~/.claude/skills/<name>/SKILL.md
# Claude Code requires skills to be in a subdirectory with the file named SKILL.md
CLAUDE_SKILLS="$CLAUDE_DIR/skills"
if [[ -L "$CLAUDE_SKILLS" ]]; then
  warn "~/.claude/skills was a symlink — replacing with real directory"
  rm "$CLAUDE_SKILLS"
fi
mkdir -p "$CLAUDE_SKILLS"
skill_count=0
for skill_file in "$SKILLS_DIR"/*.md; do
  [[ -f "$skill_file" ]] || continue
  skill_name="$(basename "$skill_file" .md)"
  skill_dest="$CLAUDE_SKILLS/$skill_name"
  mkdir -p "$skill_dest"
  cp "$skill_file" "$skill_dest/SKILL.md"
  skill_count=$((skill_count + 1))
done
# Directory-format skills (*/SKILL.md) — copy SKILL.md into place
for skill_dir in "$SKILLS_DIR"/*/; do
  [[ -f "$skill_dir/SKILL.md" ]] || continue
  skill_name="$(basename "$skill_dir")"
  skill_dest="$CLAUDE_SKILLS/$skill_name"
  # Already a symlink to this source dir (e.g. speckit-*): leave it alone
  if [[ -L "$skill_dest" && "$(readlink "$skill_dest")" == "${skill_dir%/}" ]]; then
    skill_count=$((skill_count + 1))
    continue
  fi
  [[ -L "$skill_dest" ]] && rm "$skill_dest"
  mkdir -p "$skill_dest"
  cp "$skill_dir/SKILL.md" "$skill_dest/SKILL.md"
  skill_count=$((skill_count + 1))
done
info "~/.claude/skills/ — installed $skill_count skill(s) from $SKILLS_DIR"

# Global CLAUDE.md
CLAUDE_MD="$CLAUDE_DIR/CLAUDE.md"
backup "$CLAUDE_MD"
build_instructions "Claude Code" > "$CLAUDE_MD"
info "~/.claude/CLAUDE.md written"

# ── Gemini CLI ────────────────────────────────────────────────────────────────

section "Gemini CLI"

# Skills: copy each *.md into ~/.gemini/skills/<name>/SKILL.md
# Gemini CLI follows a similar pattern to Claude Code for user skills
GEMINI_SKILLS="$GEMINI_DIR/skills"
if [[ -L "$GEMINI_SKILLS" ]]; then
  warn "~/.gemini/skills was a symlink — replacing with real directory"
  rm "$GEMINI_SKILLS"
fi
mkdir -p "$GEMINI_SKILLS"
skill_count=0
for skill_file in "$SKILLS_DIR"/*.md; do
  [[ -f "$skill_file" ]] || continue
  skill_name="$(basename "$skill_file" .md)"
  skill_dest="$GEMINI_SKILLS/$skill_name"
  mkdir -p "$skill_dest"
  cp "$skill_file" "$skill_dest/SKILL.md"
  skill_count=$((skill_count + 1))
done
for skill_dir in "$SKILLS_DIR"/*/; do
  [[ -f "$skill_dir/SKILL.md" ]] || continue
  skill_name="$(basename "$skill_dir")"
  skill_dest="$GEMINI_SKILLS/$skill_name"
  [[ -L "$skill_dest" ]] && rm "$skill_dest"
  mkdir -p "$skill_dest"
  cp "$skill_dir/SKILL.md" "$skill_dest/SKILL.md"
  skill_count=$((skill_count + 1))
done
info "~/.gemini/skills/ — installed $skill_count skill(s) from $SKILLS_DIR"

# Global GEMINI.md
GEMINI_MD="$GEMINI_DIR/GEMINI.md"
backup "$GEMINI_MD"
build_instructions "Gemini CLI" > "$GEMINI_MD"
info "~/.gemini/GEMINI.md written"

# ── Hermes ────────────────────────────────────────────────────────────────────

section "Hermes"

# Skills: symlinks so Hermes always reflects the latest source
# Flat *.md skills → symlink to ~/.claude/skills/<name> (the installed copy)
# Directory skills → symlink directly to source dir in ai-toolbox
HERMES_SKILLS="$HERMES_DIR/skills"
mkdir -p "$HERMES_SKILLS"
skill_count=0
for skill_file in "$SKILLS_DIR"/*.md; do
  [[ -f "$skill_file" ]] || continue
  skill_name="$(basename "$skill_file" .md)"
  skill_dest="$HERMES_SKILLS/$skill_name"
  rm -rf "$skill_dest"
  ln -s "$CLAUDE_SKILLS/$skill_name" "$skill_dest"
  skill_count=$((skill_count + 1))
done
for skill_dir in "$SKILLS_DIR"/*/; do
  [[ -f "$skill_dir/SKILL.md" ]] || continue
  skill_name="$(basename "$skill_dir")"
  skill_dest="$HERMES_SKILLS/$skill_name"
  rm -rf "$skill_dest"
  ln -s "${skill_dir%/}" "$skill_dest"
  skill_count=$((skill_count + 1))
done
info "~/.hermes/skills/ — installed $skill_count skill(s) as symlinks from $SKILLS_DIR"

# ── Cursor ────────────────────────────────────────────────────────────────────

section "Cursor"

# Project skills for headless cursor-agent inbox jobs

CURSOR_PROJECT_SKILLS="/Users/haimengzhou/apps/ai-console/.cursor/skills"
ORCHESTRATE_INBOX_SKILLS=(inbox-log-analyzer daily-inbox-digest task-orchestrate orchestrate-daily-wiki-ingest)
mkdir -p "$CURSOR_PROJECT_SKILLS"
for skill_name in "${ORCHESTRATE_INBOX_SKILLS[@]}"; do
  skill_src="$SKILLS_DIR/$skill_name/SKILL.md"
  [[ -f "$skill_src" ]] || continue
  skill_dest="$CURSOR_PROJECT_SKILLS/$skill_name"
  mkdir -p "$skill_dest"
  cp "$skill_src" "$skill_dest/SKILL.md"
done
info "$CURSOR_PROJECT_SKILLS — synced ${#ORCHESTRATE_INBOX_SKILLS[@]} inbox skill(s) for cursor-agent"

backup "$CURSOR_RULES"
build_instructions "Cursor" > "$CURSOR_RULES"
info "~/.cursorrules written"

# ── Done ─────────────────────────────────────────────────────────────────────

echo
echo "Done. To add a skill: drop a .md file or directory in $SKILLS_DIR"
echo "To update global instructions: edit files in $INSTRUCTIONS_DIR, then re-run sync.sh"
